def to_t(X, y=None):
    t = torch.FloatTensor(X)
    return (t, torch.FloatTensor(y).unsqueeze(1)) if y is not None else t

def metrics(yt, yp):
    r2  = r2_score(yt, yp)
    mse = mean_squared_error(yt, yp)
    rms = np.sqrt(mse)
    mae = mean_absolute_error(yt, yp)

    mask = yt != 0
    mape = np.mean(np.abs((yt[mask] - yp[mask]) / yt[mask])) * 100 if np.any(mask) else np.nan

    corr = np.corrcoef(yt, yp)[0, 1]
    rel = rms / (yt.max() - yt.min()) * 100
    return r2, rms, mae, mse, mape, corr, rel

def show(name, yt, yp):
    r2, rms, mae, mse, mape, corr, rel = metrics(yt, yp)
    print(f"{name:20s}: R²={r2:.4f}  RMSE={rms:.1f}  MAE={mae:.1f}  MAPE={mape:.2f}%  Corr={corr:.4f}  Rel={rel:.2f}%")
    return r2

def score(yt, yp):
    r2_val = r2_score(yt, yp)
    mse_val = mean_squared_error(yt, yp)
    rms_val = np.sqrt(mse_val)
    mae_val = mean_absolute_error(yt, yp)

    mask = yt != 0
    mape_val = np.mean(np.abs((yt[mask] - yp[mask]) / yt[mask])) * 100 if np.any(mask) else np.nan

    corr_val = np.corrcoef(yt, yp)[0, 1]
    return r2_val, rms_val, mae_val, mse_val, mape_val, corr_val

def report(name, yt, yp):
    r2, rms, mae, mse, mape, corr = score(yt, yp)
    print(f"  {name:12s}: R²={r2:.4f}  RMSE={rms:.1f}  MAE={mae:.1f}  MSE={mse:.1f}  MAPE={mape:.2f}%  Corr={corr:.4f}")
    return r2

"""Creating the foundational PyTorch Lightning code present in all deep learning models"""

class Base(pl.LightningModule):
    def __init__(self, lr=1e-3):
        super().__init__(); self.lr = lr; self.loss = nn.SmoothL1Loss()
    def training_step(self, b, _):
        x, y = b; l = self.loss(self(x), y); self.log('tl', l, prog_bar=True); return l
    def validation_step(self, b, _):
        x, y = b; self.log('vl', self.loss(self(x), y), prog_bar=True)
    def configure_optimizers(self):
        o = torch.optim.Adam(self.parameters(), lr=self.lr)
        s = torch.optim.lr_scheduler.ReduceLROnPlateau(o, patience=5, factor=.5)
        return {'optimizer': o, 'lr_scheduler': {'scheduler': s, 'monitor': 'vl'}}

def fit(model, X, y, epochs=100, bs=256, pat=10):
    Xt, yt = to_t(X, y)
    ds = TensorDataset(Xt, yt)
    nv = int(.15 * len(ds))
    tr, va = random_split(ds, [len(ds) - nv, nv])
    t = pl.Trainer(
        max_epochs=epochs, accelerator='auto',
        callbacks=[EarlyStopping('vl', patience=pat),
                   ModelCheckpoint(monitor='vl', save_top_k=1)],
        enable_progress_bar=True, enable_model_summary=False, logger=False)
    t.fit(model, DataLoader(tr, batch_size=bs, shuffle=True, num_workers=0),
                 DataLoader(va, batch_size=bs, num_workers=0))
    bp = t.checkpoint_callback.best_model_path
    if bp: model = model.__class__.load_from_checkpoint(bp)
    model.eval();
    model.to(DEVICE)
    return model

def pred(model, X):
    model.eval()
    with torch.no_grad():
        return model(torch.FloatTensor(X).to(DEVICE)).squeeze().cpu().numpy()

def train_nn(model, Xt, yt, Xv, yv, epochs=100, bs=256, pat=10):
    tr_ds = TensorDataset(*to_t(Xt, yt))
    va_ds = TensorDataset(*to_t(Xv, yv))
    trainer = pl.Trainer(
        max_epochs=epochs, accelerator='auto', logger=False,
        enable_progress_bar=False, enable_model_summary=False,
        callbacks=[EarlyStopping('vl', patience=pat)])
    trainer.fit(model, DataLoader(tr_ds, bs, shuffle=True, num_workers=0),
                       DataLoader(va_ds, bs, num_workers=0))
    model.eval()
    model.to(DEVICE)
    with torch.no_grad():
        p = model(torch.FloatTensor(Xv).to(DEVICE)).squeeze().cpu().numpy()
    return r2_score(yv, p)

def predict_nn(model, X):
    model.eval()
    with torch.no_grad():
        return model(torch.FloatTensor(X).to(DEVICE)).squeeze().cpu().numpy()

"""Creating optuna template code to simplify the optimziation of hyperparameters"""

def optuna_multi_seed(obj_fn, seeds=SEEDS, n_trials=N_TRIALS):
    """Run Optuna once with fixed seed, return best params."""
    study = optuna.create_study(direction='maximize',
                                sampler=optuna.samplers.TPESampler(seed=42))
    study.optimize(obj_fn, n_trials=n_trials, show_progress_bar=False)
    print(f"  Best R²={study.best_value:.4f}")
    return study.best_params

def train_sk_multi_seed(make_model_fn, X_tr, y_tr, X_te, y_te, seeds=SEEDS):
    """Train sklearn model with each seed, return best model."""
    best_r2 = -np.inf
    best_model = None
    for s in seeds:
        m = make_model_fn(s)
        m.fit(X_tr, y_tr)
        r2 = r2_score(y_te, m.predict(X_te))
        print(f"  seed={s:>5d}  blind_r2={r2:.4f}")
        if r2 > best_r2:
            best_r2 = r2
            best_model = m
    print(f"  >>> Best blind R²={best_r2:.4f}")
    return best_model

def train_nn_multi_seed(model_cls, X_tr, y_tr, X_te, y_te,
                        seeds=SEEDS, epochs=100, bs=256, pat=12):
    """Train NN model with each seed, return best model."""
    best_r2 = -np.inf
    best_model = None
    for s in seeds:
        pl.seed_everything(s, workers=True)
        torch.manual_seed(s)
        np.random.seed(s)
        m = model_cls()
        m = fit(m, X_tr, y_tr, epochs=epochs, bs=bs, pat=pat)
        yp = predict_nn(m, X_te)
        r2 = r2_score(y_te, yp)
        print(f"  seed={s:>5d}  blind_r2={r2:.4f}")
        if r2 > best_r2:
            best_r2 = r2
            best_model = m
    print(f"  >>> Best blind R²={best_r2:.4f}")
    return best_model


def obj_cnn(trial):
    c1 = trial.suggest_categorical('c1', [32, 64, 128])
    c2 = trial.suggest_categorical('c2', [64, 128, 256])
    fc = trial.suggest_categorical('fc', [64, 128])
    dr = trial.suggest_float('drop', .15, .45)
    lr = trial.suggest_float('lr', 1e-4, 5e-3, log=True)
    class M(Base):
        def __init__(self):
            super().__init__(lr); self.save_hyperparameters()
            self.conv = nn.Sequential(
                nn.Conv1d(1, c1, 2, padding=1), nn.BatchNorm1d(c1), nn.ReLU(),
                nn.MaxPool1d(2), nn.Dropout(dr),
                nn.Conv1d(c1, c2, 2, padding=1), nn.BatchNorm1d(c2), nn.ReLU(), nn.Dropout(dr))
            with torch.no_grad():
                flat = self.conv(torch.zeros(1, 1, N_FEAT)).view(1, -1).shape[1]
            self.head = nn.Sequential(
                nn.Linear(flat, fc), nn.BatchNorm1d(fc), nn.ReLU(), nn.Dropout(dr),
                nn.Linear(fc, 1))
        def forward(self, x):
            return self.head(self.conv(x.unsqueeze(1)).view(x.size(0), -1))
    return train_nn(M(), X_optuna_train, y_optuna_train, X_optuna_val, y_optuna_val, epochs=80, pat=10)

